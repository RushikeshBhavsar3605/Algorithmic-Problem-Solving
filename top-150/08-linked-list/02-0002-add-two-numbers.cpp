template <typename Node> void print(Node *head) {
    Node *curr = head;
    while (curr) {
        cout << curr->val;
        if (curr->next)
            cout << " -> ";
        curr = curr->next;
    }
    cout << endl;
}

class ListNode {
  public:
    int val;
    ListNode *next;
    ListNode(int val) {
        this->val = val;
        next = nullptr;
    }
};

/* Approach (Math + Two Pointer): */
class Solution {
  public:
    ListNode *addTwoNumbers(ListNode *l1, ListNode *l2) {
        ListNode *newhead = new ListNode(-1);
        ListNode *curr = newhead;
        int carry = 0;

        while (l1 || l2 || carry) {
            int sum = carry;

            if (l1) {
                sum += l1->val;
                l1 = l1->next;
            }

            if (l2) {
                sum += l2->val;
                l2 = l2->next;
            }

            curr->next = new ListNode(sum % 10);
            carry = sum / 10;

            curr = curr->next;
        }

        return newhead->next;
    }
};

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ListNode *num1 = new ListNode(2);
    num1->next = new ListNode(4);
    num1->next->next = new ListNode(3);

    ListNode *num2 = new ListNode(5);
    num2->next = new ListNode(6);
    num2->next->next = new ListNode(4);

    Solution obj;
    auto res = obj.addTwoNumbers(num1, num2);
    print(res);
    return 0;
}

